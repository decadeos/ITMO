function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    children: [new TextRun({ text, bold: true, size: 32, font: "Arial" })],
    spacing: { before: 400, after: 200 },
  });
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    children: [new TextRun({ text, bold: true, size: 26, font: "Arial", color: "1F4E79" })],
    spacing: { before: 300, after: 160 },
  });
}

function h3(text) {
  return new Paragraph({
    children: [new TextRun({ text, bold: true, size: 24, font: "Arial", color: "2E75B6" })],
    spacing: { before: 200, after: 100 },
  });
}

function p(text) {
  return new Paragraph({
    children: [new TextRun({ text, size: 22, font: "Arial" })],
    spacing: { after: 120 },
  });
}

function pBold(text) {
  return new Paragraph({
    children: [new TextRun({ text, size: 22, font: "Arial", bold: true })],
    spacing: { after: 80 },
  });
}

function bullet(text, bold = false) {
  return new Paragraph({
    numbering: { reference: "bullets", level: 0 },
    children: [new TextRun({ text, size: 22, font: "Arial", bold })],
    spacing: { after: 80 },
  });
}

function note(text) {
  return new Paragraph({
    children: [new TextRun({ text: "💡 " + text, size: 22, font: "Arial", italics: true, color: "555555" })],
    spacing: { after: 120, before: 80 },
    indent: { left: 360 },
  });
}

function pageBreak() {
  return new Paragraph({ children: [new PageBreak()] });
}

function divider() {
  return new Paragraph({
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: "BBBBBB" } },
    spacing: { before: 200, after: 200 },
    children: [],
  });
}

